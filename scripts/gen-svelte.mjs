// Generates the Svelte 4 and 5 component wrappers (src/svelte/components/*.svelte) and,
// with --dist, dist/svelte/index.js + index.d.ts. The component list and prop
// types are read from the React bindings so the ports stay 1:1.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const react = readFileSync(join(root, "src/react/index.ts"), "utf8");
export const components = [...react.matchAll(/export const (\w+) = create<(\w+)>\("(\w+)"\)/g)].map(
  ([, name, type]) => ({ name, type }),
);
const models = {
  GlassSwitch: ["checked"],
  GlassSlider: ["value"],
  GlassTabBar: ["value"],
  GlassSegmented: ["value"],
  GlassSearch: ["value"],
  GlassMenu: ["open"],
  GlassSheet: ["open"],
};

const slots = {
  GlassButton: ["icon", "trailing"],
  GlassMenu: ["trigger"],
  GlassMenuItem: ["icon", "shortcut"],
};
const tagOf = (name) => name.replace(/[A-Z]/g, (m, i) => (i ? "-" : "") + m.toLowerCase());
const prettierBin = join(root, "node_modules/prettier/bin/prettier.cjs");

const formatted = new Map();

function formatSvelte(source) {
  if (!existsSync(prettierBin)) return source;
  return execFileSync(process.execPath, [prettierBin, "--stdin-filepath", "Component.svelte"], {
    cwd: root,
    input: source,
    encoding: "utf8",
  });
}

// DOM events forwarded for Svelte 4 style `on:click` (Svelte 5 parents pass `onclick` instead).
export const forwarded = [
  "click",
  "dblclick",
  "focus",
  "blur",
  "focusin",
  "focusout",
  "keydown",
  "keyup",
  "pointerdown",
  "pointerup",
  "pointerenter",
  "pointerleave",
  "mouseenter",
  "mouseleave",
  "input",
  "change",
];

// Components are written in Svelte's classic (non-runes) syntax on purpose:
// - the same file compiles in Svelte 4 and Svelte 5 (Svelte 5 runs it in legacy mode),
// - only classic components can render children passed with `slot="…"` (e.g. the
//   menu trigger); in runes mode the named-slot content is unreachable and <slot>
//   is deprecated. Svelte 5 parents can still use runes, snippets/children,
//   `bind:` and `onclick`-style props with them.
export function component({ name }) {
  const hit = formatted.get(name);
  if (hit) return hit;
  const models_ = models[name] ?? [];
  const setArgs = models_.length ? "prop, v" : "_prop, _v";
  const source = formatSvelte(`<!-- Generated by scripts/gen-svelte.mjs - do not edit. -->
<script>
  import { glassProps, svelteProps } from "../actions.js";
  /** The underlying custom element (\`bind:element\`). */
  export let element = null;
${models_.map((m) => `  export let ${m} = undefined;`).join("\n")}
  $: split = svelteProps("${name}", $$restProps, { ${models_.join(", ")} }, (${setArgs}) => {
${models_.map((m) => `    if (prop === "${m}") ${m} = v;`).join("\n")}
  });
</script>

<!-- The custom element sets its own role (button, switch, slider, …) at runtime. -->
<!-- svelte-ignore a11y-no-static-element-interactions -->
<${tagOf(name)} bind:this={element} {...split.html} {...split.ssr} use:glassProps={split.own} ${forwarded.map((e) => `on:${e}`).join(" ")}><slot />${(slots[name] ?? []).map((x) => `<slot name="${x}" />`).join("")}</${tagOf(name)}>
`);
  formatted.set(name, source);
  return source;
}

const dir = join(root, "src/svelte/components");
const generated = components.map((c) => [c.name, component(c)]);
rmSync(dir, { recursive: true, force: true });
mkdirSync(dir, { recursive: true });
for (const [name, source] of generated) writeFileSync(join(dir, `${name}.svelte`), source);

if (process.argv.includes("--dist")) {
  const out = join(root, "dist/svelte");
  const js = [
    "// Svelte 4 and 5 components + actions.",
    ...components.map(
      (c) => `export { default as ${c.name} } from "./components/${c.name}.svelte";`,
    ),
    'export * from "./actions.js";',
    "",
  ].join("\n");
  const types = [...new Set(components.map((c) => c.type))];
  const dts = `import { SvelteComponent } from "svelte";
import type { HTMLAttributes } from "svelte/elements";
import type { ${types.join(", ")} } from "../bindings/specs.js";

type Base<P> = Omit<HTMLAttributes<HTMLElement>, keyof P | "children"> & { element?: HTMLElement | null };
// Component classes work for Svelte 4 and 5 type checking, including \`slot="…"\`
// children (menu trigger, icons) and forwarded \`on:click\`-style events.
type Events = { ${forwarded.map((e) => `${e}: ${/^(click|dblclick|mouseenter|mouseleave)$/.test(e) ? "MouseEvent" : /^pointer/.test(e) ? "PointerEvent" : /^key/.test(e) ? "KeyboardEvent" : /^focus|^blur/.test(e) ? "FocusEvent" : "Event"}`).join("; ")} };
${components.map((c) => `export declare class ${c.name} extends SvelteComponent<${c.type} & Base<${c.type}>, Events, { ${["default", ...(slots[c.name] ?? [])].map((x) => `${x}: {}`).join("; ")} }> {}`).join("\n")}

export * from "./actions.js";
export type { GlassAttributes, GlassButtonProps, GlassItemProps, GlassMenuItemProps, GlassMenuProps, GlassProgressiveBlurProps, GlassSceneProps, GlassSearchProps, GlassSelectorProps, GlassSheetProps, GlassSliderProps, GlassSurfaceProps, GlassSwitchProps } from "../bindings/specs.js";

/** Lets \`<glass-*>\` tags with \`use:glassProps\` type-check (Svelte 4 and 5). */
declare module "svelte/elements" {
  interface SvelteHTMLElements {
${components.map((c) => `    "${c.name.replace(/[A-Z]/g, (m, i) => (i ? "-" : "") + m.toLowerCase())}": HTMLAttributes<HTMLElement> & { [attr: string]: unknown };`).join("\n")}
  }
}
`;
  mkdirSync(join(out, "components"), { recursive: true });
  writeFileSync(join(out, "index.js"), js);
  writeFileSync(join(out, "index.d.ts"), dts);
  for (const c of components)
    writeFileSync(join(out, "components", `${c.name}.svelte`), component(c));
}
console.log(`svelte: ${components.length} components`);
